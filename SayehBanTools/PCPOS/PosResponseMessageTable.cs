    /// <summary>پیام فارسی کد پاسخ؛ «""» یعنی پیامی برای این ترکیب تعریف نشده (مثل کد قدیمی).</summary>
    public static bool TryGetMessage(string company, string responseCode, string actionCode, string rrn, out string message)
    {
